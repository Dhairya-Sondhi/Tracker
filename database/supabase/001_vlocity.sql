-- Run once in the Supabase SQL editor. Supabase Auth owns credentials and sessions.
create extension if not exists pgcrypto;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text,
  role text not null default 'USER' check (role in ('ADMIN','USER')),
  is_active boolean not null default true,
  session_version integer not null default 1,
  last_login_at timestamptz,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.trackers (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name varchar(140) not null,
  detail varchar(255) not null default '',
  type text not null check (type in ('BOOLEAN','NUMBER','DURATION','RATING','COUNT','TIME')),
  target_value numeric(14,3),
  unit varchar(30) not null default '',
  sort_order integer not null default 0,
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists trackers_user_active_idx on public.trackers(user_id,is_archived);

create table if not exists public.tracker_entries (
  id bigint generated by default as identity primary key,
  tracker_id bigint not null references public.trackers(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  entry_date date not null,
  numeric_value numeric(14,3),
  boolean_value boolean,
  status text not null default 'PENDING' check (status in ('COMPLETE','PARTIAL','MISSED','PLANNED_SKIP','REST_DAY','PENDING')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(tracker_id,entry_date)
);
create index if not exists entries_user_date_idx on public.tracker_entries(user_id,entry_date desc);

create table if not exists public.weekly_plan_items (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  tracker_id bigint not null references public.trackers(id) on delete cascade,
  planned_date date not null,
  created_at timestamptz not null default now(),
  unique(tracker_id,planned_date)
);
create index if not exists weekly_plan_user_date_idx on public.weekly_plan_items(user_id,planned_date);

create table if not exists public.user_top_focus (
  user_id bigint primary key references public.users(id) on delete cascade,
  tracker_id bigint not null references public.trackers(id) on delete cascade,
  updated_at timestamptz not null default now()
);

create table if not exists public.user_settings (
  user_id bigint primary key references public.users(id) on delete cascade,
  theme text not null default 'dark' check (theme in ('dark','light','system')),
  default_planning_view text not null default 'DAY' check (default_planning_view in ('DAY','WEEK','MONTH')),
  week_start_day smallint not null default 1 check (week_start_day in (0,1)),
  animations_enabled boolean not null default true,
  compact_mode boolean not null default false,
  timezone varchar(64) not null default 'Asia/Kolkata',
  email_digest text not null default 'WEEKLY' check (email_digest in ('OFF','DAILY','WEEKLY')),
  weekly_review_reminder boolean not null default true,
  daily_reminder_time time,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id bigint references public.users(id) on delete set null,
  target_user_id bigint references public.users(id) on delete set null,
  action varchar(80) not null,
  metadata jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_created_idx on public.admin_audit_logs(created_at desc);

create table if not exists public.auth_rate_limits (
  scope varchar(48) not null,
  key_hash char(64) not null,
  window_started_at timestamptz not null default now(),
  attempts integer not null default 1,
  blocked_until timestamptz,
  updated_at timestamptz not null default now(),
  primary key(scope,key_hash)
);

create table if not exists public.notification_deliveries (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  kind text not null check (kind in ('DAILY_PROGRESS','WEEKLY_PROGRESS','WEEKLY_REVIEW')),
  period_key varchar(64) not null,
  status text not null default 'SENDING' check (status in ('SENDING','SENT','FAILED')),
  attempts integer not null default 1 check (attempts between 1 and 5),
  provider_message_id text,
  last_error varchar(500),
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,kind,period_key)
);
create index if not exists notification_deliveries_user_created_idx on public.notification_deliveries(user_id,created_at desc);

create or replace function public.touch_updated_at() returns trigger language plpgsql set search_path=public as $$
begin new.updated_at=now();return new;end $$;
drop trigger if exists users_touch_updated_at on public.users;
create trigger users_touch_updated_at before update on public.users for each row execute function public.touch_updated_at();
drop trigger if exists trackers_touch_updated_at on public.trackers;
create trigger trackers_touch_updated_at before update on public.trackers for each row execute function public.touch_updated_at();
drop trigger if exists entries_touch_updated_at on public.tracker_entries;
create trigger entries_touch_updated_at before update on public.tracker_entries for each row execute function public.touch_updated_at();

create or replace function public.handle_new_auth_user() returns trigger language plpgsql security definer set search_path=public as $$
declare profile_id bigint; display_value text;
begin
 display_value=coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'),''),split_part(coalesce(new.email,''),'@',1));
 insert into public.users(auth_user_id,email,display_name) values(new.id,lower(new.email),display_value) returning id into profile_id;
 insert into public.user_settings(user_id) values(profile_id);
 insert into public.trackers(user_id,name,detail,type,target_value,unit,sort_order) values
  (profile_id,'Wake before 7','Before 7:00 AM','BOOLEAN',1,'',1),
  (profile_id,'Morning routine','6 step ritual','BOOLEAN',1,'',2),
  (profile_id,'Gym','Movement · 45 min','BOOLEAN',1,'',3),
  (profile_id,'Water','Daily target · 3 L','NUMBER',3,'L',4),
  (profile_id,'Study','Daily target · 120 min','DURATION',120,'min',5),
  (profile_id,'Reading','Daily target · 30 pages','NUMBER',30,'pages',6),
  (profile_id,'Meditation','Daily target · 15 min','DURATION',15,'min',7),
  (profile_id,'Mood','How today feels','RATING',10,'/10',8);
 insert into public.admin_audit_logs(target_user_id,action) values(profile_id,'USER_SIGNED_UP');
 return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_auth_user();

