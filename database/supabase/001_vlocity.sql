create or replace function public.current_profile_id() returns bigint language sql stable security definer set search_path=public as $$select id from public.users where auth_user_id=(select auth.uid()) and is_active$$;
drop policy if exists users_self_read on public.users;
create policy users_self_read on public.users for select to authenticated using(id=(select public.current_profile_id()));
drop policy if exists trackers_owner on public.trackers;
create policy trackers_owner on public.trackers for all to authenticated using(user_id=(select public.current_profile_id())) with check(user_id=(select public.current_profile_id()));
drop policy if exists entries_owner on public.tracker_entries;
create policy entries_owner on public.tracker_entries for all to authenticated using(user_id=(select public.current_profile_id())) with check(user_id=(select public.current_profile_id()));
drop policy if exists plans_owner on public.weekly_plan_items;
create policy plans_owner on public.weekly_plan_items for all to authenticated using(user_id=(select public.current_profile_id())) with check(user_id=(select public.current_profile_id()));
drop policy if exists focus_owner on public.user_top_focus;
create policy focus_owner on public.user_top_focus for all to authenticated using(user_id=(select public.current_profile_id())) with check(user_id=(select public.current_profile_id()));
drop policy if exists settings_owner on public.user_settings;
create policy settings_owner on public.user_settings for all to authenticated using(user_id=(select public.current_profile_id())) with check(user_id=(select public.current_profile_id()));

