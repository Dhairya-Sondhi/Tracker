insert into public.users(auth_user_id,email,display_name)
select id,lower(email),coalesce(nullif(trim(raw_user_meta_data->>'display_name'),''),split_part(email,'@',1))
from auth.users where email is not null
on conflict do nothing;
insert into public.user_settings(user_id) select id from public.users on conflict do nothing;

create or replace function public.consume_auth_rate_limit(p_scope text,p_key_hash text,p_limit integer,p_window_seconds integer,p_block_seconds integer)
returns table(attempts integer,retry_after integer) language plpgsql security definer set search_path=public as $$
declare row_state public.auth_rate_limits%rowtype;
begin
 if p_limit<1 or p_window_seconds<1 or p_block_seconds<1 then raise exception 'invalid rate limit';end if;
 insert into public.auth_rate_limits(scope,key_hash) values(p_scope,p_key_hash) on conflict do nothing;
 select * into row_state from public.auth_rate_limits where scope=p_scope and key_hash=p_key_hash for update;
 if row_state.blocked_until>now() then
  return query select row_state.attempts,greatest(0,ceil(extract(epoch from row_state.blocked_until-now()))::integer);return;
 end if;
 if row_state.window_started_at<now()-make_interval(secs=>p_window_seconds) then row_state.attempts=1;row_state.window_started_at=now();row_state.blocked_until=null;
 else row_state.attempts=row_state.attempts+1;if row_state.attempts>p_limit then row_state.blocked_until=now()+make_interval(secs=>p_block_seconds);end if;end if;
 update public.auth_rate_limits set attempts=row_state.attempts,window_started_at=row_state.window_started_at,blocked_until=row_state.blocked_until,updated_at=now() where scope=p_scope and key_hash=p_key_hash;
 return query select row_state.attempts,greatest(0,coalesce(ceil(extract(epoch from row_state.blocked_until-now()))::integer,0));
end $$;

create or replace function public.replace_weekly_plan(p_user_id bigint,p_start date,p_end date,p_items jsonb)
returns void language plpgsql security definer set search_path=public as $$
begin
 if p_end<p_start then raise exception 'invalid plan range';end if;
 if exists(select 1 from jsonb_to_recordset(p_items) as x(tracker_id bigint,planned_date date) left join public.trackers t on t.id=x.tracker_id and t.user_id=p_user_id and not t.is_archived where t.id is null or x.planned_date not between p_start and p_end) then raise exception 'invalid tracker or date';end if;
 delete from public.weekly_plan_items where user_id=p_user_id and planned_date between p_start and p_end;
 insert into public.weekly_plan_items(user_id,tracker_id,planned_date) select p_user_id,x.tracker_id,x.planned_date from jsonb_to_recordset(p_items) as x(tracker_id bigint,planned_date date);
end $$;

create or replace function public.update_managed_user(p_actor_id bigint,p_target_id bigint,p_role text,p_is_active boolean)
returns void language plpgsql security definer set search_path=public as $$
declare target public.users%rowtype; active_admins integer;
begin
 if p_actor_id=p_target_id then raise exception 'SELF_MANAGEMENT_NOT_ALLOWED';end if;
 select * into target from public.users where id=p_target_id for update;if not found then raise exception 'USER_NOT_FOUND';end if;
 perform id from public.users where role='ADMIN' and is_active order by id for update;
 select count(*) into active_admins from public.users where role='ADMIN' and is_active;
 if target.role='ADMIN' and target.is_active and (coalesce(p_role,target.role)<>'ADMIN' or coalesce(p_is_active,target.is_active)=false) and active_admins<=1 then raise exception 'LAST_ADMIN';end if;
 update public.users set role=coalesce(p_role,role),is_active=coalesce(p_is_active,is_active),session_version=session_version+1 where id=p_target_id;
 insert into public.admin_audit_logs(actor_user_id,target_user_id,action,metadata) values(p_actor_id,p_target_id,'USER_ACCESS_UPDATED',jsonb_build_object('role',p_role,'isActive',p_is_active));
end $$;

create or replace function public.update_user_settings(p_user_id bigint,p_display_name text,p_theme text,p_default_planning_view text,p_week_start_day smallint,p_animations_enabled boolean,p_compact_mode boolean,p_timezone text,p_email_digest text,p_weekly_review_reminder boolean,p_daily_reminder_time time)
returns void language plpgsql security definer set search_path=public as $$
begin
 update public.users set display_name=p_display_name where id=p_user_id;
 if not found then raise exception 'USER_NOT_FOUND';end if;
 insert into public.user_settings(user_id,theme,default_planning_view,week_start_day,animations_enabled,compact_mode,timezone,email_digest,weekly_review_reminder,daily_reminder_time)
 values(p_user_id,p_theme,p_default_planning_view,p_week_start_day,p_animations_enabled,p_compact_mode,p_timezone,p_email_digest,p_weekly_review_reminder,p_daily_reminder_time)
 on conflict(user_id) do update set theme=excluded.theme,default_planning_view=excluded.default_planning_view,week_start_day=excluded.week_start_day,animations_enabled=excluded.animations_enabled,compact_mode=excluded.compact_mode,timezone=excluded.timezone,email_digest=excluded.email_digest,weekly_review_reminder=excluded.weekly_review_reminder,daily_reminder_time=excluded.daily_reminder_time,updated_at=now();
end $$;

create or replace function public.claim_notification_delivery(p_user_id bigint,p_kind text,p_period_key text)
returns bigint language plpgsql security definer set search_path=public as $$
declare claimed_id bigint;
begin
 insert into public.notification_deliveries(user_id,kind,period_key)
 values(p_user_id,p_kind,p_period_key)
 on conflict(user_id,kind,period_key) do update
 set status='SENDING',attempts=public.notification_deliveries.attempts+1,last_error=null,updated_at=now()
 where public.notification_deliveries.attempts<5 and (
  public.notification_deliveries.status='FAILED' or
  (public.notification_deliveries.status='SENDING' and public.notification_deliveries.updated_at<now()-interval '15 minutes')
 )
 returning id into claimed_id;
 return claimed_id;
end $$;

